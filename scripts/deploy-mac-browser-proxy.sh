#!/usr/bin/env bash
# Deploy the home proxy that the agents' Playwright browsers load pages through.
#
# On the OpenClaw server, each browser has no route out except a relay to this
# proxy (ansible/roles/playwright), so pages load from this Mac's home
# connection instead of a data-centre address that sites often block.
#
# The proxy (squid) listens only on this Mac's tailnet address, serves only the
# server's tailnet address, allows only ports 80 and 443, and refuses private,
# tailnet and loopback addresses and this home network's own IPv6 ranges, so a
# page cannot reach this Mac or other devices at home. The home IPv6 ranges are
# read each time the proxy starts; restart it after the provider changes them.
#
# Settings: openclaw_playwright_proxy in ansible/group_vars/openclaw.yml
# (host = this Mac's tailnet IPv4, port, client = the server's tailnet IPv4),
# the same block the server's provisioning checks.
#
# squid runs as a system LaunchDaemon under this account, so it keeps running
# while nobody is logged in (see deploy-mac-daemons.sh). Needs Homebrew squid
# and yq. Idempotent and re-runnable.
#
# Usage:
#   ./scripts/deploy-mac-browser-proxy.sh                 # install or update, then verify
#   ./scripts/deploy-mac-browser-proxy.sh --status
#   ./scripts/deploy-mac-browser-proxy.sh --uninstall
#   ./scripts/deploy-mac-browser-proxy.sh --print-config  # the squid.conf it would write
#
# Env: BROWSER_PROXY_HOST, BROWSER_PROXY_PORT, BROWSER_PROXY_CLIENT override
# openclaw.yml (used by the tests); CONF_DIR, BIN_DIR, LOG_DIR override paths.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
OPENCLAW_YML="$SCRIPT_DIR/../ansible/group_vars/openclaw.yml"
ACCOUNT="$(id -un)"
LABEL="com.openclaw.browser-proxy.${ACCOUNT}"
PLIST="/Library/LaunchDaemons/${LABEL}.plist"
: "${CONF_DIR:=$HOME/.config/openclaw-browser-proxy}"
: "${BIN_DIR:=$HOME/.local/bin}"
: "${LOG_DIR:=$HOME/Library/Logs/openclaw}"
RUNNER="$BIN_DIR/openclaw-browser-proxy-run"

die() { echo "ERROR: $*" >&2; exit 1; }
log() { echo "==> $*"; }

setting() {  # $1 = key under openclaw_playwright_proxy, $2 = env override
    if [ -n "${!2:-}" ]; then echo "${!2}"; return; fi
    command -v yq >/dev/null || die "yq is required (brew install yq)"
    [ -f "$OPENCLAW_YML" ] || die "openclaw.yml not found: $OPENCLAW_YML"
    yq -r ".openclaw_playwright_proxy.$1 // \"\"" "$OPENCLAW_YML"
}

load_settings() {
    HOST="$(setting host BROWSER_PROXY_HOST)"
    PORT="$(setting port BROWSER_PROXY_PORT)"
    CLIENT="$(setting client BROWSER_PROXY_CLIENT)"
    local ipv4='^([0-9]{1,3}\.){3}[0-9]{1,3}$'
    [[ "$HOST" =~ $ipv4 ]] || die "openclaw_playwright_proxy.host must be this Mac's tailnet IPv4, got '$HOST'"
    [[ "$CLIENT" =~ $ipv4 ]] || die "openclaw_playwright_proxy.client must be the server's tailnet IPv4, got '$CLIENT'"
    [[ "$PORT" =~ ^[0-9]+$ ]] || die "openclaw_playwright_proxy.port must be a number, got '$PORT'"
}

# Every range a page must not reach from here. IPv4-mapped (::ffff:0:0/96) is left
# out on purpose: squid folds it into 0.0.0.0/0 and would refuse every site.
render_config() {
    cat <<EOF
# Generated by scripts/deploy-mac-browser-proxy.sh in openclaw-infra. Do not edit.
http_port ${HOST}:${PORT}
visible_hostname openclaw-browser-proxy
httpd_suppress_version_string on
pid_filename ${CONF_DIR}/squid.pid
cache_log ${LOG_DIR}/browser-proxy.log
cache deny all
cache_mem 8 MB
shutdown_lifetime 2 seconds

acl openclaw_server src ${CLIENT}/32
acl safe_ports port 80 443
acl tls_port port 443
acl CONNECT method CONNECT
acl blocked_dst dst 0.0.0.0/8 10.0.0.0/8 100.64.0.0/10 127.0.0.0/8 169.254.0.0/16 172.16.0.0/12 192.0.0.0/24 192.168.0.0/16 198.18.0.0/15 224.0.0.0/3
acl blocked_dst dst ::/128 ::1/128 64:ff9b::/96 fc00::/7 fe80::/10 ff00::/8
acl blocked_dst dst "${CONF_DIR}/home-ipv6.acl"

http_access deny !openclaw_server
http_access deny !safe_ports
http_access deny CONNECT !tls_port
http_access deny blocked_dst
http_access allow openclaw_server
http_access deny all

# Log refusals only: enough to debug a blocked page, without a browsing history.
acl refused http_status 403
access_log stdio:${LOG_DIR}/browser-proxy-refused.log refused

# Sites see the home connection, not the server or the Mac's name.
forwarded_for delete
via off
EOF
}

# launchd runs this at every start: write the home IPv6 ranges, then become squid.
# `--write-acl` only writes them, so deploy can validate the real ranges first.
render_runner() {
    cat <<EOF
#!/bin/bash
# Generated by scripts/deploy-mac-browser-proxy.sh in openclaw-infra. Do not edit.
set -euo pipefail
# Global IPv6 networks of this Mac: devices at home have addresses there. Each line
# is address/prefixlen as ifconfig reports it; squid masks off the host part.
ranges=\$(/sbin/ifconfig | /usr/bin/awk '\$1 == "inet6" && \$2 ~ /^[23][0-9a-fA-F]*:/ {
    for (i = 3; i < NF; i++) if (\$i == "prefixlen") print \$2 "/" \$(i + 1) }' | /usr/bin/sort -u)
# squid needs at least one entry; ::/128 matches nothing a page can reach.
printf '%s\n' "\${ranges:-::/128}" > "${CONF_DIR}/home-ipv6.acl"
[ "\${1:-}" = --write-acl ] && exit 0
exec "$SQUID" -N -f "${CONF_DIR}/squid.conf"
EOF
}

render_plist() {
    cat <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>${LABEL}</string>
    <key>UserName</key>
    <string>${ACCOUNT}</string>
    <key>ProgramArguments</key>
    <array>
        <string>${RUNNER}</string>
    </array>
    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <true/>
    <key>ThrottleInterval</key>
    <integer>10</integer>
    <key>StandardOutPath</key>
    <string>${LOG_DIR}/browser-proxy.out.log</string>
    <key>StandardErrorPath</key>
    <string>${LOG_DIR}/browser-proxy.out.log</string>
</dict>
</plist>
EOF
}

sudo_prime() {
    sudo -n -v 2>/dev/null && return 0
    [ -n "${SUDO_ASKPASS:-}" ] && sudo -A -v 2>/dev/null && return 0
    sudo -v || die "sudo is needed to install ${PLIST}"
}

deploy() {
    load_settings
    SQUID="$(brew --prefix squid 2>/dev/null)/sbin/squid"
    [ -x "$SQUID" ] || die "squid is not installed (brew install squid)"
    /sbin/ifconfig | grep -q "inet ${HOST} " || die "${HOST} is not an address of this Mac; check openclaw_playwright_proxy.host"
    mkdir -p "$CONF_DIR" "$BIN_DIR" "$LOG_DIR"
    chmod 700 "$CONF_DIR"
    render_config > "$CONF_DIR/squid.conf"
    render_runner > "$RUNNER"
    chmod 755 "$RUNNER"
    # Validate with the real home ranges before replacing the running proxy.
    "$RUNNER" --write-acl
    "$SQUID" -k parse -f "$CONF_DIR/squid.conf" >"$CONF_DIR/parse.log" 2>&1 \
        || { cat "$CONF_DIR/parse.log" >&2; die "squid rejected the generated config"; }
    local tmp
    tmp="$(mktemp)"
    render_plist > "$tmp"
    plutil -lint "$tmp" >/dev/null
    sudo_prime
    sudo install -o root -g wheel -m 644 "$tmp" "$PLIST"
    rm -f "$tmp"
    sudo launchctl bootout "system/${LABEL}" 2>/dev/null || true
    for _ in 1 2 3 4 5; do
        sudo launchctl bootstrap system "$PLIST" && break
        sleep 1
    done
    sudo launchctl print "system/${LABEL}" >/dev/null || die "launchd did not load ${LABEL}"
    verify
}

# The proxy must answer, and must refuse this Mac: only the server may use it.
verify() {
    load_settings
    local code=""
    for _ in $(seq 1 20); do
        code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 -x "http://${HOST}:${PORT}" http://example.com/ || true)
        [ "$code" = 403 ] && break
        sleep 1
    done
    [ "$code" = 403 ] || die "the proxy on ${HOST}:${PORT} did not answer with 403 for this Mac (got '${code}'); see ${LOG_DIR}/browser-proxy.log"
    log "proxy up on ${HOST}:${PORT}, serving only ${CLIENT}; home IPv6 ranges refused: $(tr '\n' ' ' < "$CONF_DIR/home-ipv6.acl")"
}

status() {
    sudo launchctl print "system/${LABEL}" 2>/dev/null | grep -E '^\s+(state|pid|last exit code)' || echo "not loaded: ${LABEL}"
    verify
}

uninstall() {
    sudo_prime
    sudo launchctl bootout "system/${LABEL}" 2>/dev/null || true
    sudo rm -f "$PLIST"
    rm -f "$RUNNER"
    rm -rf "$CONF_DIR"
    log "removed ${LABEL} (logs kept in ${LOG_DIR})"
}

case "${1:-}" in
    "") deploy ;;
    --status) status ;;
    --uninstall) uninstall ;;
    --print-config) load_settings; render_config ;;
    *) die "unknown option: $1 (see the usage at the top of this script)" ;;
esac
